/// @brief literal value is pushed on stack
/// @param lit literal node
static void literal_generate(node *lit) {

  if (lit->as.lit.type == TYPE_INT) {
    pushs_(operand_int(lit->as.lit.i));
  } else if (lit->as.lit.type == TYPE_DOUBLE) {
    pushs_(operand_float(lit->as.lit.d));
  } else if (lit->as.lit.type == TYPE_STRING) {
    pushs_(operand_string(lit->as.lit.s));
  } else if (lit->as.lit.type == TYPE_UNIT) {
    pushs_(operand_nil());
  } else if (lit->as.lit.type == TYPE_BOOLEAN) {
    pushs_(operand_bool(lit->as.lit.b != 0));
  } else {
    gen_error(ERR_INTERNAL, lit);
  }
}

/// @brief value of variable is pushed on stack
/// @param id identifier node
static void identifier_generate(node *id) {

  if (id->func != NULL && id->var == NULL) {
    call_(operand_function(id->as.ident.name, NULL));
    return;
  }
  pushs_(operand_variable(node_variable_get(id)));
}

// generates code for unary operations

/// @brief unary operators, multiplies by -1 of the same type
/// @param ctx generation context
/// @param expr unary operation node
static void unary_generate(gen_context *ctx, node *expr) {
  if (expr->as.unar.op != OP_NEGATE && expr->as.unar.op != OP_NOT) {
    gen_error(ERR_INTERNAL, expr);
  }

  expression_generate(ctx, expr->as.unar.operand);
  if (expr->as.unar.op == OP_NOT) {
    nots_();
    return;
  }

  if (expr->data_type == TYPE_DOUBLE) {
    pushs_(operand_float(-1.0));
  } else {
    pushs_(operand_int(-1));
  }
  muls_();
}

/// @brief && and || , if left operand choses the result, right operand is not
/// evaluated, and chosing value is result -> pushed on stack
/// @param ctx generation context
/// @param expr node of && or ||
static void boolthen_generate(gen_context *ctx, node *expr) {
  int boolthen_label = ctx->label_cnt++;
  char *type = "and";
  bool decided = false;

  if (expr->as.binar.op == OP_OR) {
    type = "or";
    decided = true;
  }

  expression_generate(ctx, expr->as.binar.left);
  pushs_(operand_bool(decided));
  jumpifeqs_(operand_numbered(type, boolthen_label, "short"));
  expression_generate(ctx, expr->as.binar.right);
  jump_(operand_numbered("end", boolthen_label, "end"));
  label_(operand_numbered(type, boolthen_label, "short"));
  pushs_(operand_bool(decided));
  label_(operand_numbered("end", boolthen_label, "end"));
}

/// @brief operands are evaluated left to right, result is pushed on stack,
/// expression_generate where sematics prompts
/// @param ctx generation context
/// @param expr binary operation node
static void binary_generate(gen_context *ctx, node *expr) {
  operator bin_operator = expr->as.binar.op;

  if (expr->as.binar.op == OP_AND || expr->as.binar.op == OP_OR) {
    boolthen_generate(ctx, expr);
    return;
  }
  expression_generate(ctx, expr->as.binar.left);
  expression_generate(ctx, expr->as.binar.right);

  if (bin_operator == OP_ADD && expr->data_type == TYPE_STRING) {
    concat_();
  } else if (bin_operator == OP_ADD) {
    adds_();
  } else if (bin_operator == OP_SUBTRACT) {
    subs_();
  } else if (bin_operator == OP_MULTIPLY) {
    muls_();
  } else if (bin_operator == OP_DIVIDE && expr->data_type == TYPE_INT) {
    idivs_();
  } else if (bin_operator == OP_DIVIDE) {
    divs_();
  } else if (bin_operator == OP_EQUAL) {
    eqs_();
  } else if (bin_operator == OP_LESSER) {
    lts_();
  } else if (bin_operator == OP_GREATER) {
    gts_();
  } else if (bin_operator == OP_NOT_EQUAL) {
    eqs_();
    nots_();
  } else if (bin_operator == OP_LESSER_OR_EQUAL) {
    gts_();
    nots_();
  } else if (bin_operator == OP_GREATER_OR_EQUAL) {
    lts_();
    nots_();
  } else {
    gen_error(ERR_INTERNAL, expr);
  }
}

/// @brief arguments are evaluated left to right on stack, extkw gets receiver
/// as first argument has label $type$name, FUNEXP, PARAMLISTS, then CALL
/// @param ctx generation context
/// @param call call node
static void call_generate(gen_context *ctx, node *call) {

  for (int i = 0; i < call->as.call.size; i++) {
    expression_generate(ctx, call->as.call.items[i]);
  }
  call_(operand_function(call->as.call.name, NULL));
}

/// @brief VALMEM built in function that calls value.toString, value.toInt,
/// value.length. value.floor calls $floor, if semantics linked the member to a
/// method of an extension without parameters .. EXTKW , the method is called
/// @param ctx generation context
/// @param expr expression node
static void valmem_generate(gen_context *ctx, node *expr) {
  char *valmem = expr->as.member.name;
  expression_generate(ctx, expr->as.member.obj);

  if (expr->func != NULL) {
    call_(operand_method(receiver_method_type_name(expr->as.member.obj), valmem,
                         NULL));

  } else if (strcmp(valmem, "toInt") == 0) {
    call_(operand_function("toInt", NULL));
  } else if (strcmp(valmem, "toString") == 0) {
    call_(operand_function("toStr", NULL));
  } else if (strcmp(valmem, "length") == 0) {
    call_(operand_function("strLength", NULL));
  } else if (strcmp(valmem, "floor") == 0) {
    printf("call $floor\n");
  } else {
    gen_error(ERR_INTERNAL, expr);
  }
}

/// @brief generates expression, value ends on top of stack, if semantics
/// prompted conversion to double, int2float is called
/// @param ctx generation context
/// @param expr expression node
static void expression_generate(gen_context *ctx, node *expr) {
  if (expr->type == node_lit) {
    literal_generate(expr);
  } else if (expr->type == node_call) {
    call_generate(ctx, expr);
  } else if (expr->type == node_if) {
    if_generate(ctx, expr, true);
  } else if (expr->type == node_expression) {
    expression_generate(ctx, expr->as.expression.expression);
  } else if (expr->type == node_id) {
    identifier_generate(expr);
  } else if (expr->type == node_binar) {
    binary_generate(ctx, expr);
  } else if (expr->type == node_unar) {
    unary_generate(ctx, expr);
  } else if (expr->type == node_member) {
    valmem_generate(ctx, expr);
  } else {
    gen_error(ERR_INTERNAL, expr);
  }
  if (expr->convert_to_double) {
    int2floats_();
  }
}

