// operand types of IFJcode26 instruction used in code generator
typedef enum {
  OPERAND_INT,
  OPERAND_STRING,
  OPERAND_NIL,
  OPERAND_FUNCTION,
  OPERAND_FLOAT,
  OPERAND_VARIABLE,
  OPERAND_BOOL,
  OPERAND_NUMBERED,
  OPERAND_METHOD

} gen_operand_type;

// operand of IFJcode26 instruction, printed by print_operand function
typedef struct {
  gen_operand_type type;
  union {

    // LF@name$number
    struct {
      char *name;
      int number;
    } variable;

    // int@int_value
    int int_value;

    // float@float_value
    double float_value;

    // string@string_value
    char *string_value;

    // bool@true/false
    bool bool_value;

    char *label;

    // fn$name/fn$name$part
    struct {
      char *name;
      char *part;
    } function;

    // if / while / || / && $type$number$part
    struct {
      char *type;
      int number;
      char *part;
    } numbered;

    // method of extension $type$name$part
    struct {
      char *type;
      char *name;
      char *part;
    } method;
  } as;
} gen_operand;

// state of code generator, to keep track of labels, current function and type
// of receiver for method calls
typedef struct {
  node *program;
  node *function;
  int label_cnt;
  char *received_type;
} gen_context;

/// @brief Prints error message to stderr and exits, only prints internal errors
/// @param err Error code
/// @param n Node to refer on
static void gen_error(error_code err, node *n) {
  const char *message = error_to_message(err);
  if (n == NULL) {
    fprintf(stderr, "%s\n", message);
  } else {
    fprintf(stderr, "%s at row %i column %i\n", message, n->row, n->column);
  }
  exit(err);
}

