/// @brief transforms reciever type to its name used in labels of methods,
/// TYPE_INT -> Integer ...
/// @param type Data type of the receiver
/// @return name of the type or internal error
static char *method_type_name(data_types type) {

  if (type == TYPE_BOOLEAN) {
    return "Boolean";
  } else if (type == TYPE_INT) {
    return "Integer";
  } else if (type == TYPE_DOUBLE) {
    return "Double";
  } else if (type == TYPE_STRING) {
    return "String";
  } else if (type == TYPE_UNIT) {
    return "Unit";
  } else {
    gen_error(ERR_INTERNAL, NULL);
    return NULL;
  }
}

/// @brief name of type of receiver, int receiver of method Double is converted
/// by expression_generate so its type is TYPE_DOUBLE
/// @param received node
/// @return name of the type for label of called method
static char *receiver_method_type_name(node *received) {

  if (received->convert_to_double) {
    return "Double";
  }
  return method_type_name(received->data_type);
}

/// @brief find the function @main in program
/// @param program ast node
/// @return node of the @main function or NULL if none
static node *find_main(node *program) {
  for (int i = 0; i < program->as.program.size; i++) {
    node *function = program->as.program.items[i];
    if (function != NULL && function->type == node_function &&
        function->as.function.is_main) {
      return function;
    }
  }
  return NULL;
}

/// @brief prints string literal constant with IFJcode26 format, # and \ are as
/// \xyz
/// @param str string literal to print
static void print_string_literal(char *str) {
  for (int i = 0; str[i] != '\0'; i++) {

    if (str[i] == '#') {
      printf("\\035");
    } else if (str[i] == '\\') {
      printf("\\092");
    } else if (str[i] >= 0 && str[i] <= 32) {
      printf("\\%03d", str[i]);
    } else {
      printf("%c", str[i]);
    }
  }
}

/// @brief prints operand based on its type
/// @param operand operand to print
static void print_operand(gen_operand operand) {

  if (operand.type == OPERAND_INT) {
    printf("int@%d", operand.as.int_value);
  } else if (operand.type == OPERAND_VARIABLE) {
    printf("LF@%s$%d", operand.as.variable.name, operand.as.variable.number);
  } else if (operand.type == OPERAND_STRING) {
    printf("string@");
    print_string_literal(operand.as.string_value);
  } else if (operand.type == OPERAND_NIL) {
    printf("nil@nil");
  } else if (operand.type == OPERAND_FLOAT) {
    printf("float@%a", operand.as.float_value);
  } else if (operand.type == OPERAND_FUNCTION) {
    printf("fn$%s", operand.as.function.name);

    if (operand.as.function.part != NULL) {
      printf("$%s", operand.as.function.part);
    }
  } else if (operand.type == OPERAND_BOOL) {
    if (operand.as.bool_value) {
      printf("bool@true");
    } else {
      printf("bool@false");
    }
  } else if (operand.type == OPERAND_NUMBERED) {

    printf("$%s$%d$%s", operand.as.numbered.type, operand.as.numbered.number,
           operand.as.numbered.part);
  } else if (operand.type == OPERAND_METHOD) {
    printf("$%s$%s", operand.as.method.type, operand.as.method.name);

    if (operand.as.method.part != NULL) {
      printf("$%s", operand.as.method.part);
    }
  } else {
    gen_error(ERR_INTERNAL, NULL);
  }
}

/// @brief prints one instruction in one line code and operands separated by
/// space
/// @param code code of the instruction
/// @param cnt number of operands
/// @param operands array of operands
static void write_instruction(char *code, int cnt, gen_operand *operands) {
  printf("%s", code);
  for (int i = 0; i < cnt; i++) {
    putchar(' ');
    print_operand(operands[i]);
  }
  putchar('\n');
}

