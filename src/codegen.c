/// @brief label of the generated function fn$name or $type$name when method of
/// extension is generated
/// @param ctx generation context
/// @param label label suffix, NULL for function alone
/// @return operand of the function label
static gen_operand function_label(gen_context *ctx, char *label) {
  return operand_function(node_function_get(ctx->function)->name, label);
}

/// @brief function with return type unit returns (), value on stack is trashed
/// and nil@nil is pushed instead
/// @param ctx generation context
static void set_return_type(gen_context *ctx) {

  if (node_function_get(ctx->function)->return_type == TYPE_UNIT) {
    trash_();
    pushs_(operand_nil());
  }
}

/// @brief initial value is stored in variable (variable is defined by DEFVAR at
/// the beggining of the function))
/// @param ctx generation context
/// @param stmnt node of the definition of variable with initial value
static void var_val_generate(gen_context *ctx, node *stmnt) {
  expression_generate(ctx, stmnt->as.val_var.init);
  pops_(operand_variable(node_variable_get(stmnt)));
}

/// @brief stores the value on right side to variable
/// @param ctx generation context
/// @param stmnt node of the assignment
static void assign_generate(gen_context *ctx, node *stmnt) {
  expression_generate(ctx, stmnt->as.asign.init);
  pops_(operand_variable(node_variable_get(stmnt)));
}

/// @brief returned value stays on top of the stack, code jumps to the end of
/// function
/// @param ctx generation context
/// @param stmnt node of return
static void return_generate(gen_context *ctx, node *stmnt) {
  if (stmnt->as.ret.value != NULL) {
    expression_generate(ctx, stmnt->as.ret.value);
  } else {
    pushs_(operand_nil());
  }

  set_return_type(ctx);
  jump_(function_label(ctx, "end"));
}

static void block_generate(gen_context *ctx, node *block, bool is_keep_value);

/// @brief while cycle, condition evaluation before every iteration
/// @param ctx generation context
/// @param stmnt node of the while statement
// while block
// label while$num$start
// expression
// pushs false
// jumpifeqs while$num$end
// block
// jump while$num$start
// label while$num$end
static void while_generate(gen_context *ctx, node *stmnt) {

  int while_label = ctx->label_cnt++;

  label_(operand_numbered("while", while_label, "start"));
  expression_generate(ctx, stmnt->as.while_n.condition);
  pushs_(operand_bool(false));
  jumpifeqs_(operand_numbered("while", while_label, "end"));
  block_generate(ctx, stmnt->as.while_n.body, false);
  jump_(operand_numbered("while", while_label, "start"));
  label_(operand_numbered("while", while_label, "end"));
}

/// @brief if statement, the else part can be missing and else if is an if in
/// else block
/// @param ctx generation context
/// @param stmnt node of the if statement
// expression
// pushs false
// jumpifeqs if$num$else
// block
// jump if$num$end
// label if$num$else
// block
// label if$num$end
static void if_generate(gen_context *ctx, node *stmnt, bool is_keep_value) {

  int if_label = ctx->label_cnt++;
  expression_generate(ctx, stmnt->as.if_n.condition);
  pushs_(operand_bool(false));
  jumpifeqs_(operand_numbered("if", if_label, "else"));
  block_generate(ctx, stmnt->as.if_n.then, is_keep_value);
  jump_(operand_numbered("if", if_label, "end"));
  label_(operand_numbered("if", if_label, "else"));
  if (stmnt->as.if_n.else_n != NULL) {
    block_generate(ctx, stmnt->as.if_n.else_n, is_keep_value);
  } else if (is_keep_value) {
    pushs_(operand_nil());
  }
  label_(operand_numbered("if", if_label, "end"));
}

/// @brief checks if for cycle ends, compares loop variable with end variable, if the condition is met, jumps to the end label
/// @param loop_variable variable of the loop cycle
/// @param end_variable end variable of the loop cycle
/// @param until true if the loop is until, false if the loop is to
/// @param descend true if step is negative, counts down
/// @param end_label lable behind the for cycle
static void for_end_generate(gen_operand loop_variable,
                             gen_operand end_variable, bool until, bool descend,
                             gen_operand end_label) {

  pushs_(loop_variable);
  pushs_(end_variable);
  if (descend != until) {
    lts_();
  } else {
    gts_();
  }
  pushs_(operand_bool(!until));
  jumpifeqs_(end_label);
}


/// @brief CONTROL, 
/// @param ctx generation context
/// @param stmnt node of the for statement

// expression from, pops i
// expression to, pops $for_end
// expression step, pops $for_step
// step != 0, jump for$num$start, else exit int@40
// label for$num$start
// step < 0, jump for$num$down
// end check up
// jump for$num$body
// label for$num$down
// end check down
// label for$num$body
// guards, false, jump for$num$next
// block
// label for$num$next
// i = i + step
// jump for$num$start
// label for$num$end
static void for_generate(gen_context *ctx, node *stmnt) {
  int for_label = ctx->label_cnt++;
  gen_operand end_variable = operand_variable(stmnt->as.for_n.end_var);
  gen_operand loop_variable = operand_variable(node_variable_get(stmnt));
  gen_operand step = operand_int(1);
  gen_operand end_label = operand_numbered("for", for_label, "end");
  bool until = !stmnt->as.for_n.inclusive;

  // evaluate only once
  expression_generate(ctx, stmnt->as.for_n.from);
  pops_(loop_variable);
  expression_generate(ctx, stmnt->as.for_n.to);
  pops_(end_variable);

  // step evaluated once, else error 40
  if (stmnt->as.for_n.step != NULL) {
    step = operand_variable(stmnt->as.for_n.step_var);
    expression_generate(ctx, stmnt->as.for_n.step);
    pops_(step);

    pushs_(step);
    pushs_(operand_int(0));
    jumpifneqs_(operand_numbered("for", for_label, "start"));
    exit_(operand_int(40));
  }

  label_(operand_numbered("for", for_label, "start"));

  //
  if (stmnt->as.for_n.step != NULL) {
    pushs_(step);
    pushs_(operand_int(0));
    lts_();
    pushs_(operand_bool(true));
    jumpifeqs_(operand_numbered("for", for_label, "down"));
    for_end_generate(loop_variable, end_variable, until, false, end_label);
    jump_(operand_numbered("for", for_label, "body"));
    label_(operand_numbered("for", for_label, "down"));
    for_end_generate(loop_variable, end_variable, until, true, end_label);
    label_(operand_numbered("for", for_label, "body"));
  } else {
    for_end_generate(loop_variable, end_variable, until, false, end_label);
  }
  for (int i = 0; i < stmnt->as.for_n.guard_count; i++) {
    expression_generate(ctx, stmnt->as.for_n.guards[i]);
    pushs_(operand_bool(false));
    jumpifeqs_(operand_numbered("for", for_label, "next"));
  }
  block_generate(ctx, stmnt->as.for_n.body, false);

  // i = i + step
  label_(operand_numbered("for", for_label, "next"));
  pushs_(loop_variable);
  pushs_(step);
  adds_();
  pops_(loop_variable);
  jump_(operand_numbered("for", for_label, "start"));
  label_(end_label);
}

/// @brief generates code for one statement, value of expression or call is
/// trashed
/// @param ctx generation context
/// @param stmnt statement node
static void statement_generate(gen_context *ctx, node *stmnt) {
  if (stmnt->type == node_expression || stmnt->type == node_call) {
    expression_generate(ctx, stmnt);
    trash_();
  } else if (stmnt->type == node_val_var) {
    var_val_generate(ctx, stmnt);
  } else if (stmnt->type == node_asign) {
    assign_generate(ctx, stmnt);
  } else if (stmnt->type == node_return) {
    return_generate(ctx, stmnt);
  } else if (stmnt->type == node_while) {
    while_generate(ctx, stmnt);
  } else if (stmnt->type == node_if) {
    if_generate(ctx, stmnt, false);
  } else if (stmnt->type == node_for) {
    for_generate(ctx, stmnt);
  } else {
    gen_error(ERR_INTERNAL, stmnt);
  }
}

/// @brief generates all statements of a block, if / while / for parts or
/// function body
/// @param ctx generation context
/// @param block node of the block
/// @param is_keep_value if true, the value of the last statement is kept on the
/// stack as result (also the value of the last if, CONTROL), a block ending
/// with another statement has result nil@nil
static void block_generate(gen_context *ctx, node *block, bool is_keep_value) {
  int cnt = block->as.block.size;
  for (int i = 0; i < cnt; i++) {

    node *stmnt = block->as.block.items[i];
    bool is_last = (i == cnt - 1);

    if (is_keep_value && is_last &&
        (stmnt->type == node_expression || stmnt->type == node_call)) {
      expression_generate(ctx, stmnt);
    } else if (is_keep_value && is_last && stmnt->type == node_if) {
      if_generate(ctx, stmnt, true);
    } else {
      statement_generate(ctx, stmnt);
      if (is_last && is_keep_value) {
        pushs_(operand_nil());
      }
    }
  }

  if (cnt == 0 && is_keep_value) {
    pushs_(operand_nil());
  }
}

// ----- generation of functions and whole program

/// @brief generates code for a function, new local frame, DEFVAR for all local
/// variables, arguments are popped from stack last to first, then body. its
/// value is return value left on stack, EXTKW has receiver as extra first
/// argument
/// @param ctx generation context
/// @param fn node of the function
static void function_generate(gen_context *ctx, node *fn) {
  sym_function *function_entry = node_function_get(fn);
  ctx->function = fn;

  // beginning of function
  label_(function_label(ctx, NULL));
  createframe_();
  pushframe_();

  for (int i = 0; i < function_entry->locals_count; i++) {
    defvar_(operand_variable(function_entry->locals[i]));
  }

  // error handling of parameters
  int param_count = function_entry->parameter_count;
  if (function_entry->locals_count < param_count) {
    gen_error(ERR_INTERNAL, fn);
  }
  for (int i = 0; i < param_count; i++) {
    if (!function_entry->locals[i]->is_parameter) {
      gen_error(ERR_INTERNAL, fn);
    }
  }

  //  loop to pop params to locals from last to first
  for (int i = param_count - 1; i >= 0; i--) {
    pops_(operand_variable(function_entry->locals[i]));
  }
  block_generate(ctx, fn->as.function.body, true);
  set_return_type(ctx);

  // end of function
  label_(function_label(ctx, "end"));
  popframe_();
  return_();

  ctx->function = NULL;
}

/// @brief generates whole code of the program in IFJcode26 to output
/// @param program node of the program
void code_generate(struct node *program) {

  node *main_function = find_main(program);
  if (main_function == NULL) {
    gen_error(ERR_INTERNAL, program);
  }
  gen_context ctx = {.program = program};

  // IFJ header
  printf(".IFJcode26\n");

  for (int i = 0; gen_global_temp[i] != NULL; i++) {
    printf("defvar GF@%s\n", gen_global_temp[i]);
  }

  // program is call of @main, after the return interpretation ends, exit code 0
  call_(operand_function(main_function->as.function.name, NULL));
  exit_(operand_int(0));

  for (int i = 0; gen_library[i] != NULL; i++) {
    printf("%s\n", gen_library[i]);
  }

  // generates all functions and methods of the program
  for (int i = 0; i < program->as.program.size; i++) {
    node *item = program->as.program.items[i];
    if (item->type == node_extension) {
      ctx.received_type = method_type_name(item->as.extension.type);
      for (int j = 0; j < item->as.extension.size; j++) {
        function_generate(&ctx, item->as.extension.methods[j]);
      }
      ctx.received_type = NULL;
    } else {
      function_generate(&ctx, program->as.program.items[i]);
    }
  }
}