// generates all statements of a block, if / while parts or body of function
static void block_generate(gen_context *ctx, node *block, bool is_keep_value) {
  int cnt = block->as.block.size;
  for (int i = 0; i < cnt; i++) {

    node *stmnt = block->as.block.items[i];
    bool is_last = (i == cnt - 1);

    if (is_keep_value && is_last && stmnt->type == node_expression ||
        stmnt->type == node_call) {
      expression_generate(ctx, stmnt);
    } else {
      statement_generate(ctx, stmnt);
      if (is_last && is_keep_value) {
        pushs_(operand_nil());
      }
    }
  }

  if (cnt == 0 && is_keep_value) {
    pushs_(operand_nil());
  }
}

// ----- generation of functions and whole program

static void function_generate(gen_context *ctx, node *fn) {
  char *name = fn->as.function.name;
  sym_function *function_entry = node_function_get(fn);
  ctx->function = fn;

  // beginning of function
  label_(operand_function(name, NULL));
  createframe_();
  pushframe_();

  jump_(operand_function(name, "defvars"));
  label_(operand_function(name, "body"));

  // error handling of parameters
  int param_count = fn->as.function.param_count;
  if (function_entry->locals_count < param_count) {
    internal_err(fn, "lower number of locals than parameters");
  }
  for (int i = 0; i < param_count; i++) {
    if (!function_entry->locals[i]->is_parameter) {
      internal_err(fn, "local variable is not parameter");
    }
  }

  //  loop to pop params to locals from last to first
  for (int i = param_count; i >= 0; i--) {
    pops_(operand_variable(function_entry->locals[i]));
  }
  block_generate(ctx, fn->as.function.body, true);
  set_return_type(ctx);

  // end of function
  label_(operand_function(name, "end"));
  popframe_();
  return_();

  label_(operand_function(name, "defvars"));
  for (int i = 0; i < function_entry->locals_count; i++) {
    defvar_(operand_variable(function_entry->locals[i]));
  }
  jump_(operand_function(name, "body"));
}

// generating code from AST
void code_generate(struct node *program) {

  node *main_function = find_main(program);
  if (main_function == NULL) {
    internal_err(program, "@main not found");
  }
  gen_context ctx = {.program = program};

  // IFJ header
  printf(".IFJcode26\n");

  for (int i = 0; gen_global_temp[i] != NULL; i++) {
    printf("defvar GF@%s\n", gen_global_temp[i]);
  }
  call_(operand_function(main_function->as.function.name, NULL));
  exit_(operand_int(0));

  for (int i = 0; gen_library[i] != NULL; i++) {
    printf("%s\n", gen_library[i]);
  }

  for (int i = 0; i < program->as.program.size; i++) {
    function_generate(&ctx, program->as.program.items[i]);
  }
}