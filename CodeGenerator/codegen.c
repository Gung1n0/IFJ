typedef enum
{
    OPERAND_INT,
    OPERAND_STRING,
    OPERAND_NIL,
    OPERAND_FUNCTION,
    OPERAND_LABEL,
} gen_operand_type;

typedef struct
{
    gen_operand_type type;
    union
    {

        // LF@name$number
        struct
        {
            char *name;
            int number;
        } var;

        // GF@global_name
        char *global_name;

        // int@int_value
        int int_value;

        // float@float_value
        double float_value;

        // string@string_value
        char *string_value;

        // bool@true/false
        bool bool_value;

        char *label;

        // function@name
        struct
        {
            char *name;
            char *part;
        } function;

        // type@number
        struct
        {
            char *type;
            int number;
            char *part;
        } numbered;
    } as;
} gen_operand;

