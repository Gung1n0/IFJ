// print string literal
static void print_string_literal(char *str)
{
    for (int i = 0; str[i] != '\0'; i++)
    {

        if (str[i] == '#')
        {
            printf("\\035");
        }
        else if (str[i] == '\\')
        {
            printf("\\092");
        }
        else if (str[i] >= 0 && str[i] <= 32)
        {
            printf("\\%03d", str[i]);
        }
        else
        {
            printf("%c", str[i]);
        }
    }
}

// print based on data type of operand

static void print_operand(gen_operand operand)
{
    
     if (operand.type == OPERAND_INT)
    {
        printf(" int@%d", operand.as.int_value);
    }
    else if (operand.type == OPERAND_STRING)
    {
        printf(" string@");
        print_string_literal(operand.as.string_value);
    }
    else if (operand.type == OPERAND_NIL)
    {
        printf(" nil@nil");
    }
    else if (operand.type == OPERAND_LABEL)
    {
        printf(" %s", operand.as.label);
    }
    else if (operand.type == OPERAND_FUNCTION)
    {
        printf(" fn$%s", operand.as.function);
    }
    else
    {
        internal_error(NULL, "Unknown operand type");
    }
}

