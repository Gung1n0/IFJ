typedef enum {
  OPERAND_INT,
  OPERAND_STRING,
  OPERAND_NIL,
  OPERAND_FUNCTION,
  OPERAND_FLOAT,
  OPERAND_VARIABLE,
  OPERAND_BOOL,
  OPERAND_NUMBERED

} gen_operand_type;

typedef struct {
  gen_operand_type type;
  union {

    // LF@name$number
    struct {
      char *name;
      int number;
    } variable;

    // int@int_value
    int int_value;

    // float@float_value
    double float_value;

    // string@string_value
    char *string_value;

    // bool@true/false
    bool bool_value;

    char *label;

    // function@name
    struct {
      char *name;
      char *part;
    } function;

    // type@number
    struct {
      char *type;
      int number;
      char *part;
    } numbered;
  } as;
} gen_operand;

typedef struct {
  node *program;
  node *function;

} gen_context;

