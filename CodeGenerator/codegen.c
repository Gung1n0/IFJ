static void expression_generate(gen_context *ctx, node *expr);

static void literal_generate(node *lit) {

  if (lit->as.lit.type == TYPE_INT) {
    pushs_(operand_int(lit->as.lit.i));
  } else if (lit->as.lit.type == TYPE_DOUBLE) {
    pushs_(operand_float(lit->as.lit.d));
  } else if (lit->as.lit.type == TYPE_STRING) {
    pushs_(operand_string(lit->as.lit.s));
  } else if (lit->as.lit.type == TYPE_UNIT) {
    pushs_(operand_nil());
  } else {
    internal_err(lit, "unknown literal type");
  }
}

static void identifier_generate(node *id) {
  pushs_(operand_variable(node_variable_get(id)));
}

// generates code for unary operations
static void unary_generate(gen_context *ctx, node *expr) {
  if (expr->as.unar.op != OP_NEGATE) {
    internal_err(expr, "unknown unary operator");
  }

  expression_generate(ctx, expr->as.unar.operand);
  if (expr->data_type == TYPE_DOUBLE) {
    pushs_(operand_float(-1.0));
  } else {
    pushs_(operand_int(-1));
  }
  muls_();
}

// generates code for binary operations
static void binary_generate(gen_context *ctx, node *expr) {

  expression_generate(ctx, expr->as.binar.left);
  expression_generate(ctx, expr->as.binar.right);
  operator bin_operator = expr->as.binar.op;

  if (bin_operator == OP_ADD) {
    adds_();
  } else if (bin_operator == OP_SUBTRACT) {
    subs_();
  } else if (bin_operator == OP_MULTIPLY) {
    muls_();
  } else if (bin_operator == OP_DIVIDE) {
    divs_();
  } else if (bin_operator == OP_EQUAL) {
    eqs_();
  } else if (bin_operator == OP_LESSER) {
    lts_();
  } else if (bin_operator == OP_GREATER) {
    gts_();
  } else if (bin_operator == OP_NOT_EQUAL) {
    eqs_();
    nots_();
  } else if (bin_operator == OP_LESSER_OR_EQUAL) {
    gts_();
    nots_();
  } else if (bin_operator == OP_GREATER_OR_EQUAL) {
    lts_();
    nots_();
  } else if (bin_operator == OP_DIVIDE && expr->data_type == TYPE_INT) {
    idivs_();
  } else if (bin_operator == OP_ADD && expr->data_type == TYPE_STRING) {
    concat_();
  } else {
    internal_err(expr, "unknown operator");
  }
}

// generates code call
static void call_generate(gen_context *ctx, node *call) {
  for (int i = 0; i < call->as.call.size; i++) {
    expression_generate(ctx, call->as.call.items[i]);
  }
  call_(operand_function(call->as.call.name, NULL));
}

// generated expression will be on top of stack
static void expression_generate(gen_context *ctx, node *expr) {
  if (expr->type == node_lit) {
    literal_generate(expr);
  } else if (expr->type == node_call) {
    call_generate(ctx, expr);
  } else if (expr->type == node_expression) {
    expression_generate(ctx, expr->as.expression.expression);
  } else if (expr->type == node_id) {
    identifier_generate(expr);
  } else if (expr->type == node_binar) {
    binary_generate(ctx, expr);
  } else if (expr->type == node_unar) {
    unary_generate(ctx, expr);
  } else {
    internal_err(expr, "unexpected node in expression");
  }
  if (expr->convert_to_double) {
    int2floats_();
  }
}

